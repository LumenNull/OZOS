static inline uint8_t ozos_shamir_gf_mul(uint8_t a, uint8_t b) {
    if (a == 0 || b == 0) return 0;
    return ozos_shamir_exp[ozos_shamir_log[a] + ozos_shamir_log[b]];
}

static inline uint8_t ozos_shamir_gf_div(uint8_t a, uint8_t b) {
    if (b == 0) return 0; /* Division by zero undefined in field */
    if (a == 0) return 0;
    return ozos_shamir_exp[(ozos_shamir_log[a] - ozos_shamir_log[b] + 255) % 255];
}

/* =============================================================================
   SHAMIR'S SECRET SHARING: SPLIT INTO (k, n) THRESHOLD SHARES
   ============================================================================= */

static inline int ozos_shamir_split(const uint8_t secret[OZOS_SHAMIR_SECRET_SIZE],
                                    uint8_t threshold_k,
                                    uint8_t total_n,
                                    ozos_shamir_share_t* out_shares) {
    if (!secret || !out_shares) return -1;
    if (threshold_k < OZOS_SHAMIR_MIN_THRESHOLD || threshold_k > total_n || total_n > OZOS_SHAMIR_MAX_SHARES) {
        return -2; /* Invalid threshold parameters */
    }

    memset(out_shares, 0, sizeof(ozos_shamir_share_t) * total_n);

    /* Initialize share metadata */
    for (uint8_t i = 0; i < total_n; ++i) {
        out_shares[i].magic = OZOS_SHAMIR_SHARE_MAGIC;
        out_shares[i].share_index = (uint8_t)(i + 1); /* x in 1..n */
        out_shares[i].threshold_k = threshold_k;
        out_shares[i].total_n = total_n;
    }

    /* Process each secret byte independently */
    for (size_t b_idx = 0; b_idx < OZOS_SHAMIR_SECRET_SIZE; ++b_idx) {
        uint8_t coeffs[OZOS_SHAMIR_MAX_SHARES];
        coeffs[0] = secret[b_idx]; /* f(0) = secret byte */

        /* Generate random polynomial coefficients for degree k - 1 */
        if (threshold_k > 1) {
            randombytes(coeffs + 1, threshold_k - 1);
        }

        /* Evaluate polynomial f(x) for each share x in 1..n */
        for (uint8_t s = 0; s < total_n; ++s) {
            uint8_t x = out_shares[s].share_index;
            uint8_t val = 0;
            uint8_t x_pow = 1;

            for (uint8_t deg = 0; deg < threshold_k; ++deg) {
                val ^= ozos_shamir_gf_mul(coeffs[deg], x_pow);
                x_pow = ozos_shamir_gf_mul(x_pow, x);
            }
            out_shares[s].payload[b_idx] = val;
        }

        ozos_crypto_zeroize(coeffs, sizeof(coeffs));
    }

    /* Calculate CRC16-CCITT for each share */
    for (uint8_t i = 0; i < total_n; ++i) {
        uint16_t crc = ozos_crc16_ccitt((const uint8_t*)&out_shares[i], 36);
        out_shares[i].crc16 = crc;
    }

    return 0;
}

/* =============================================================================
   SHAMIR'S SECRET SHARING: COMBINE k SHARES TO RECONSTRUCT SECRET
   ============================================================================= */

static inline int ozos_shamir_combine(const ozos_shamir_share_t* in_shares,
                                      uint8_t num_shares,
                                      uint8_t out_secret[OZOS_SHAMIR_SECRET_SIZE]) {
    if (!in_shares || !out_secret ||
        num_shares < OZOS_SHAMIR_MIN_THRESHOLD ||
        num_shares > OZOS_SHAMIR_MAX_SHARES) {
        return -1;
    }

    uint8_t k = in_shares[0].threshold_k;
    uint8_t n = in_shares[0].total_n;

    if (k < OZOS_SHAMIR_MIN_THRESHOLD ||
        k > OZOS_SHAMIR_MAX_SHARES ||
        n < k ||
        n > OZOS_SHAMIR_MAX_SHARES ||
        num_shares < k) {
        return -2; /* Insufficient or out-of-bounds shares */
    }

    /* Validate CRC16 and parameter consistency across all provided shares */
    bool seen_indices[256] = {false};
    uint8_t xs[OZOS_SHAMIR_MAX_SHARES];

    for (uint8_t i = 0; i < num_shares; ++i) {
        /* Check magic */
        if (in_shares[i].magic != OZOS_SHAMIR_SHARE_MAGIC) {
            return -3; /* Magic byte invalid */
        }
        /* Check CRC16-CCITT */
        uint16_t expected_crc = ozos_crc16_ccitt((const uint8_t*)&in_shares[i], 36);
        if (in_shares[i].crc16 != expected_crc) {
            return -4; /* CRC16 checksum mismatch (corrupted share) */
        }
        /* Check parameter matching */
        if (in_shares[i].threshold_k != k || in_shares[i].total_n != n) {
            return -5; /* Shares belong to mismatched split operations */
        }
        /* Check distinct x index within [1..n] */
        uint8_t x = in_shares[i].share_index;
        if (x == 0 || x > n || seen_indices[x]) {
            return -6; /* Duplicate, zero, or out-of-range share index */
        }
        seen_indices[x] = true;
        if (i < k) {
            xs[i] = x;
        }
    }

    /* Compute Lagrange basis coefficients ell_i(0) over GF(2^8) for the first k shares */
    uint8_t l_0[OZOS_SHAMIR_MAX_SHARES];
    for (uint8_t i = 0; i < k; ++i) {
        uint8_t num = 1;
        uint8_t den = 1;
        for (uint8_t j = 0; j < k; ++j) {
            if (i == j) continue;
            num = ozos_shamir_gf_mul(num, xs[j]);
            den = ozos_shamir_gf_mul(den, xs[i] ^ xs[j]);
        }
        l_0[i] = ozos_shamir_gf_div(num, den);
    }

    /* Reconstruct each byte of the secret via Lagrange interpolation */
    memset(out_secret, 0, OZOS_SHAMIR_SECRET_SIZE);
    for (size_t b_idx = 0; b_idx < OZOS_SHAMIR_SECRET_SIZE; ++b_idx) {
        uint8_t secret_byte = 0;
        for (uint8_t i = 0; i < k; ++i) {
            secret_byte ^= ozos_shamir_gf_mul(in_shares[i].payload[b_idx], l_0[i]);
        }
        out_secret[b_idx] = secret_byte;
    }

    return 0;
}

/* =============================================================================
   SHARE SERIALIZATION: BINARY <-> HEX
   ============================================================================= */

static inline void ozos_shamir_share_to_hex(const ozos_shamir_share_t* share, char hex_out[OZOS_SHAMIR_SHARE_HEX_LEN + 1]) {
    const uint8_t* p = (const uint8_t*)share;
    const char hex_chars[] = "0123456789abcdef";
    for (size_t i = 0; i < OZOS_SHAMIR_SHARE_RAW_LEN; ++i) {
        hex_out[i * 2]     = hex_chars[(p[i] >> 4) & 0x0F];
        hex_out[i * 2 + 1] = hex_chars[p[i] & 0x0F];
    }
    hex_out[OZOS_SHAMIR_SHARE_HEX_LEN] = '\0';
}

static inline int ozos_shamir_hex_to_share(const char* hex_in, ozos_shamir_share_t* share_out) {
    if (!hex_in || !share_out) return -1;
    size_t len = strlen(hex_in);
    if (len != OZOS_SHAMIR_SHARE_HEX_LEN) return -2;

    uint8_t* p = (uint8_t*)share_out;
    for (size_t i = 0; i < OZOS_SHAMIR_SHARE_RAW_LEN; ++i) {
        char c0 = hex_in[i * 2];
        char c1 = hex_in[i * 2 + 1];
        bool ok0 = (c0 >= '0' && c0 <= '9') || (c0 >= 'a' && c0 <= 'f') || (c0 >= 'A' && c0 <= 'F');
        bool ok1 = (c1 >= '0' && c1 <= '9') || (c1 >= 'a' && c1 <= 'f') || (c1 >= 'A' && c1 <= 'F');
        if (!ok0 || !ok1) return -3;
        char buf[3] = { c0, c1, '\0' };
        char* endptr = NULL;
        unsigned long val = strtoul(buf, &endptr, 16);
        if (!endptr || *endptr != '\0') return -3;
        p[i] = (uint8_t)val;
    }

    /* Verify CRC */
    uint16_t expected_crc = ozos_crc16_ccitt(p, 36);
    if (share_out->crc16 != expected_crc) return -4;

    return 0;
}

